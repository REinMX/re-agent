class Component(NamedTuple):
    """Tracked paths left out of the bundle on purpose. references also name it in delivered prose."""

    reason: str
    paths: frozenset[str] = frozenset()
    prefixes: tuple[str, ...] = ()
    references: tuple[str, ...] = ()
    # Delivered prose must not name these path stems. Off where the names are ordinary words or the
    # installer writes the same file in the target, so a mention is not a stranded reference.
    stems_are_references: bool = True

    def owns(self, name: str) -> bool:
        return name in self.paths or name.startswith(self.prefixes)


