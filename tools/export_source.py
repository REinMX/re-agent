#!/usr/bin/env python3
"""Export reviewed, committed source for a fresh private repository. Dry-run unless --apply.

The ZIP is a reservoir-only bundle. OMITTED_COMPONENTS names every tracked path left out on
purpose (the optional pstack plugin and checkout-only tests). PROJECTIONS rewrite the delivered
copies of the few files that instruct the reader to use an omitted component. The manifest keeps
each delivered file's original source hash next to its delivered hash and transforms.
Malformed pstack markers or a delivered instruction that still names an omitted file fail the export.

No Git history, site contract, eval results, worklogs or runtime folders are copied.
Other tracked symlinks are refused. This path filter is not a secret scanner, a license grant
or company import approval. Review exported contents and permissions before transferring them.
"""

