#!/usr/bin/env python3
"""Build deterministic pstack surfaces. No dependencies or harness calls."""

from __future__ import annotations

import argparse
import json
import os
import re
from pathlib import Path

if __package__:
    from .pstack_models import role_models
else:
    from pstack_models import role_models

ROOT = Path(__file__).resolve().parents[1]
HEADER = "GENERATED by tools/build_agent_surfaces.py - edit plugins/pstack instead"
BEGIN = "<!-- pstack:begin -->"
END = "<!-- pstack:end -->"


def metadata(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    match = re.fullmatch(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not match:
        raise ValueError(f"Invalid frontmatter: {path}")
    fields = {}
    for line in match[1].splitlines():
        key, sep, value = line.partition(":")
        if sep:
            value = value.strip()
            fields[key] = json.loads(value) if value.startswith('"') else value
    if not fields.get("name") or not fields.get("description"):
        raise ValueError(f"Missing name or description: {path}")
    return fields, match[2]


def generated(body: str, fields: dict | None = None) -> str:
    front = ""
    if fields:
        front = (
            "---\n" + "".join(f"{key}: {json.dumps(value)}\n" for key, value in fields.items()) + "---\n\n"
        )
    return front + f"<!-- {HEADER} -->\n\n" + body.rstrip() + "\n"


def surfaces(root: Path, models: dict[str, str] | None = None) -> tuple[dict[Path, str], dict[Path, str]]:
    vendor = root / "plugins/pstack"
    skills = sorted((vendor / "skills").glob("*/SKILL.md"))
    if not skills:
        raise ValueError("No vendored skills")
    files: dict[Path, str] = {}
    links: dict[Path, str] = {}
    rows = []
    for path in skills:
        fields, _ = metadata(path)
        name = fields["name"]
        source = path.relative_to(root).as_posix()
        body = f"Read and follow `{source}` and its referenced files before work.\n"
        files[Path(f".github/prompts/pstack-{name}.prompt.md")] = generated(
            body, {"description": fields["description"], "mode": "agent", "agent": "agent"}
        )
        # .claude/skills and .agents/skills already link to ../skills.
        links[Path(f"skills/pstack-{name}")] = f"../plugins/pstack/skills/{path.parent.name}"
        rows.append(f"- `{name}`: `{source}`.")
    for path in sorted((vendor / "agents").glob("*.md")):
        fields, body = metadata(path)
        name = fields["name"]
        for directory, suffix, tools in (
            (".github/agents", ".agent.md", ["read", "search", "edit", "execute", "agent"]),
            (".claude/agents", ".md", "Read, Glob, Grep, Edit, Write, Bash, Agent"),
        ):
            fm = {"description": fields["description"], "tools": tools}
            model = fields.get("model")
            if directory == ".github/agents" and not model:
                model = (models or {}).get(fields.get("model-role", "code"))
            if model and model != "inherit-parent":
                fm["model"] = model
            if directory == ".claude/agents":
                fm = {"name": name, **fm}
            files[Path(directory) / (name + suffix)] = generated(body, fm)
    agent_path = root / "AGENTS.md"
    agents = agent_path.read_text(encoding="utf-8")
    block = (
        BEGIN
        + "\n"
        + generated(
            "## pstack\n\n"
            "Use these optional workflow skills for repository work.\n\n"
            + "\n".join(rows)
            + "\n\nClaude Code discovers `skills/pstack-*` through `.claude/skills`. "
            "Codex discovers the same entries through `.agents/skills`. "
            "See `docs/PSTACK_AGENTS.md` for harness setup and limitations."
        )
        + END
    )
    if BEGIN in agents or END in agents:
        if agents.count(BEGIN) != 1 or agents.count(END) != 1 or agents.index(BEGIN) > agents.index(END):
            raise ValueError("Invalid pstack markers in AGENTS.md")
        agents = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, agents, flags=re.S)
    else:
        agents = agents.rstrip() + "\n\n" + block + "\n"
    files[Path("AGENTS.md")] = agents
    essentials = (root / "AGENTS.md").read_text(encoding="utf-8").split(BEGIN)[0]
    rules = essentials.split("## Rules\n", 1)[1].split("## Learn without changing authority", 1)[0]
    catalog = "\n".join(
        f"- `{p.parent.name}`: `{p.relative_to(root).as_posix()}`."
        for p in sorted((root / "skills").glob("*/SKILL.md"))
        if not p.parent.is_symlink()
    )
    files[Path(".github/copilot-instructions.md")] = generated(
        "# Repository instructions\n\n"
        "Read AGENTS.md and load skills/reservoir-engineer/SKILL.md first. "
        "Use continuous-learning for relevant approved lessons and earned-autonomy for done checks and retry limits. "
        "For repository code and skill work, read plugins/pstack/skills/poteto-mode/SKILL.md. "
        "Read site.contract.yml only when the task allows it; never invent site values or commit that file. "
        "On Linux VS Code, use direct mode and the read-only reservoir MCP before shell engineering checks.\n\n"
        "Cloud agents have no simulators. Do not install simulator or queue tooling there.\n\n"
        "## Repository rules from AGENTS.md\n\n"
        + rules
        + "\n## Reservoir skills\n\n"
        + catalog
        + "\n\nPstack sources: plugins/pstack/skills. Prompts: .github/prompts/pstack-*.prompt.md. "
        "Custom agents: .github/agents. See docs/PSTACK_AGENTS.md. "
        "For cloud setup, use plugins/pstack/templates/copilot-setup-steps.yml: "
        "copy this into .github/workflows/ via the GitHub web UI (Add file) to enable cloud agents."
    )
    return files, links


def link_target(path: Path) -> str:
    # Windows symlinks read back with backslashes.
    return os.readlink(path).replace("\\", "/")


def build(root: Path, check: bool = False, models: dict[str, str] | None = None) -> int:
    files, links = surfaces(root, models)
    expected = set(files) | set(links)
    stale = []
    for pattern in (".github/prompts/pstack-*.prompt.md", ".github/agents/*.agent.md", ".claude/agents/*.md"):
        stale.extend(
            p
            for p in root.glob(pattern)
            if p.relative_to(root) not in expected and HEADER in p.read_text(encoding="utf-8")
        )
    stale.extend(
        p
        for p in (root / "skills").glob("pstack-*")
        if p.is_symlink()
        and p.relative_to(root) not in expected
        and link_target(p).startswith("../plugins/pstack/skills/")
    )
    changed = [str(p.relative_to(root)) for p in stale]
    for relative, content in files.items():
        path = root / relative
        if path.is_file() and not path.is_symlink() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(str(relative))
        if not check:
            if path.is_symlink():
                raise ValueError(f"Refuse to overwrite symlink: {relative}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    for relative, target in links.items():
        path = root / relative
        if path.is_symlink() and link_target(path) == target:
            continue
        if path.is_file() and not path.is_symlink() and path.read_text(encoding="utf-8").strip() == target:
            # Git on Windows can check out a symlink as a text placeholder.
            continue
        changed.append(str(relative))
        if not check:
            if path.exists() or path.is_symlink():
                raise ValueError(f"Conflicting skill surface: {relative}")
            path.symlink_to(target, target_is_directory=True)
    if not check:
        for path in stale:
            path.unlink()
    if changed:
        print(("Out of date: " if check else "Generated: ") + ", ".join(sorted(changed)))
    return int(check and bool(changed))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--contract", type=Path, help="Opt in to agents.models for Copilot agent models")
    parser.add_argument(
        "--models", type=Path, help="Opt in to a user role file; contract values take precedence"
    )
    args = parser.parse_args()
    models = role_models(args.contract, args.models) if args.contract or args.models else None
    return build(ROOT, args.check, models)


if __name__ == "__main__":
    raise SystemExit(main())
